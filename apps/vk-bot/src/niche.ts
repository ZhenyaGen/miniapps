/**
 * Ниша и системный промпт под неё.
 *
 * Определение ниши живёт в мини-приложении — там же, где сбор данных:
 * по ней приложение ищет конкурентов, а бот настраивает модель. Копия
 * разошлась бы с оригиналом на первой же правке словаря.
 */

export { detectNiche, type Niche } from '../../vk-audit/src/vk/niche';
import type { Niche } from '../../vk-audit/src/vk/niche';

/**
 * Системный промпт под нишу.
 *
 * Общая часть неизменна и держит модель в рамках: числа только из данных,
 * без markdown, коротко. Нишевая часть добавляется сверху и меняет
 * не правила, а словарь и примеры.
 */
export function systemPrompt(niche?: Niche | string): string {
  const base = 'Ты — практикующий SMM-редактор. Пишешь по-русски, коротко и по делу, '
    + 'без канцелярита, без воды и без обращений «дорогие друзья». '
    + 'ЖЁСТКОЕ ПРАВИЛО: все числа бери только из блока ДАННЫЕ, никогда не выдумывай '
    + 'и не округляй метрики. Если данных для вывода не хватает — так и напиши. '
    + 'Это личное сообщение во ВКонтакте: без заголовков, без markdown, без списков '
    + 'со звёздочками. Обычный текст, короткие абзацы, не длиннее 1800 знаков.';

  const label = typeof niche === 'string' ? niche : niche?.label;
  if (!label) return base;

  const keywords = typeof niche === 'string' || !niche ? [] : (niche.keywords ?? []);
  const context = keywords.length
    ? ` Страница пишет о таком: ${keywords.slice(0, 8).join(', ')}.`
    : '';

  return `${base} Страница работает в нише: ${label}.${context} `
    + 'Советы и примеры тем давай именно для этой ниши, словами, которыми '
    + 'говорит её аудитория. Не предлагай форматы, которые в ней не работают, '
    + 'и не объясняй очевидное для этого рынка.';
}
