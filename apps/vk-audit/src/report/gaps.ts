/**
 * Чего на странице нет.
 *
 * Зоны роста отвечают на вопрос «что сломано». Этот список — про
 * другое: что просто не заведено. Отсутствие не попадает в метрики
 * вовсе, потому что считать нечего, и именно поэтому его легче всего
 * не заметить: нет опросов — нет и строки про опросы.
 *
 * Каждый пункт устроен одинаково: чего нет, как обстоит сейчас
 * и что это дало бы. Без последнего получается список упрёков,
 * а не предложений.
 *
 * Расчётов здесь нет — только чтение уже посчитанного, поэтому
 * эталоны питоновской версии это не трогает.
 */

import type { Metrics } from '../engine/types';
import { f } from '../engine/util';
import type { RivalsReport } from '../engine/rivals';
import type { ClipsReport } from '../video/clips';
import type { CommentReport, VideoReport } from '../video/analyze';
import type { PhotoReport } from '../photos/analyze';
import type { ContentMix } from './mix';
import { MIN_SAMPLE } from './mix';

export interface Gap {
  key: string;
  /** Чего нет — одной строкой. */
  label: string;
  /** Как обстоит сейчас: цифра, из-за которой пункт появился. */
  detail: string;
  /** Что это дало бы, если завести. */
  gain: string;
}

export interface GapsInput {
  metrics: Metrics;
  mix?: ContentMix | null;
  video?: VideoReport | null;
  clips?: ClipsReport | null;
  photos?: PhotoReport | null;
  comments?: CommentReport | null;
  rivals?: RivalsReport | null;
  /** Собирались ли медиа: без этого о форматах судить нельзя. */
  mediaCollected?: boolean;
}

export function findGaps(input: GapsInput): Gap[] {
  const { metrics: m, video, clips, photos, comments, rivals, mediaCollected } = input;
  const out: Gap[] = [];

  // ------------------------------------------------------------- форматы
  // Только когда медиа действительно читались: до разбора «нет клипов»
  // означает лишь «мы не смотрели».
  if (mediaCollected) {
    if (!clips?.count) {
      out.push({
        key: 'no-clips',
        label: 'Клипов нет вовсе',
        detail: 'За период не вышло ни одного вертикального ролика.',
        gain: 'Лента клипов — единственный источник охвата, который почти '
          + 'не зависит от числа подписчиков. Это способ показаться тем, '
          + 'кто на страницу не подписан.',
      });
    } else if (clips.count < MIN_SAMPLE) {
      out.push({
        key: 'few-clips',
        label: 'Клипы есть, но их мало',
        detail: `${clips.count} за период — судить по ним ещё нельзя.`,
        gain: 'Лента клипов раздаёт охват рывками: чтобы попасть, нужна '
          + 'серия, а не проба. Десяток клипов даст первую честную медиану.',
      });
    }

    if (!video?.count) {
      out.push({
        key: 'no-video',
        label: 'Обычного видео нет',
        detail: 'В разделе «Видео» нет ни одного своего ролика за период.',
        gain: 'Длинное видео удерживает дольше и живёт в поиске, а не только '
          + 'в ленте. Формат для того, что не помещается в клип: разборы, '
          + 'интервью, инструкции.',
      });
    }

    if (!photos?.count) {
      out.push({
        key: 'no-photos',
        label: 'Фотографий нет',
        detail: 'За период не выложено ни одного снимка.',
        gain: 'Фотография — самый дешёвый формат и единственный, который '
          + 'продолжает собирать реакции месяцами: её находят альбомами '
          + 'и поиском, когда запись уже ушла из ленты.',
      });
    }

    if (photos?.count && photos.onWall === 0) {
      out.push({
        key: 'photos-off-wall',
        label: 'Снимки не выкладываются записями',
        detail: `Все ${photos.count} снимков лежат только в альбомах.`,
        gain: 'В ленте их не видел никто из подписчиков. Готовый контент, '
          + 'который остаётся только опубликовать.',
      });
    }

    if (clips?.count && clips.offWall === clips.count) {
      out.push({
        key: 'clips-off-wall',
        label: 'Клипы не дублируются записью',
        detail: `Все ${clips.count} клипов опубликованы мимо стены.`,
        gain: 'Подписчики их в ленте сообщества не увидят — только те, '
          + 'кому клип покажет рекомендация. Дубль записью даёт второй охват '
          + 'бесплатно.',
      });
    }
  }

  // ---------------------------------------------------------- приёмы в лентe
  if (!m.polls) {
    out.push({
      key: 'no-polls',
      label: 'Опросов нет',
      detail: 'За период не вышло ни одного опроса.',
      gain: 'Опрос — самая дешёвая вовлечённость: голос требует одного '
        + 'касания, а алгоритму засчитывается как действие. Заодно это '
        + 'готовый ответ на вопрос, о чём писать дальше.',
    });
  }

  if (!m.pinned.exists) {
    out.push({
      key: 'no-pinned',
      label: 'Нет закреплённого поста',
      detail: 'Ни одна запись за период не закреплена.',
      gain: 'Закреп — единственное место, где новый человек узнаёт, куда он '
        + 'попал и зачем подписываться. Без него первый экран страницы '
        + 'занимает случайная запись.',
    });
  } else if (m.pinned.age_days !== null && m.pinned.age_days > 90) {
    out.push({
      key: 'stale-pinned',
      label: 'Закреп устарел',
      detail: `Закреплённой записи ${f(m.pinned.age_days, 0)} дней.`,
      gain: 'Свежий закреп с актуальным предложением работает как посадочная '
        + 'страница — старый просто занимает место.',
    });
  }

  if (m.cta_share < 20) {
    out.push({
      key: 'no-cta',
      label: 'Почти нет призыва к действию',
      detail: `Призыв есть только в ${f(m.cta_share, 0)}% записей.`,
      gain: 'Без просьбы люди не делают ничего — даже когда пост понравился. '
        + 'Одна строка в конце меняет долю откликов сильнее, чем переписанный '
        + 'заголовок.',
    });
  }

  if (m.questions_share < 20) {
    out.push({
      key: 'no-questions',
      label: 'Почти нет вопросов к читателю',
      detail: `Вопрос есть в ${f(m.questions_share, 0)}% записей.`,
      gain: 'Вопрос в конце — самый простой повод для комментария, '
        + 'а комментарии алгоритм считает весомее лайков.',
    });
  }

  if (!m.links_share) {
    out.push({
      key: 'no-links',
      label: 'Нет точки выхода',
      detail: 'Ни в одной записи нет ссылки.',
      gain: 'Страница ни к чему не ведёт: интерес есть, а деть его некуда. '
        + 'Даже одна ссылка на сайт или в личные сообщения делает ленту '
        + 'воронкой, а не витриной.',
    });
  }

  if (!m.hashtags.share_with) {
    out.push({
      key: 'no-tags',
      label: 'Хэштегов нет',
      detail: 'Ни одна запись не помечена тегом.',
      gain: 'Теги — бесплатная навигация по своей же ленте: рубрику можно '
        + 'открыть одним нажатием, и старые записи перестают пропадать.',
    });
  }

  // -------------------------------------------------------------- диалог
  if (comments?.posts) {
    if (!comments.fromAuthor) {
      out.push({
        key: 'no-replies',
        label: 'Автор не отвечает в комментариях',
        detail: `Разобрано веток: ${comments.posts}, ответов автора — ни одного.`,
        gain: 'Ответ считается вовлечённостью и вытягивает запись в ленте. '
          + 'Это единственная работа с охватом, которая ничего не стоит.',
      });
    }
    if (comments.unanswered.length) {
      out.push({
        key: 'unanswered',
        label: 'Есть вопросы без ответа',
        detail: `${comments.unanswered.length} вопросов остались без реакции.`,
        gain: 'Человек уже написал — дешевле вовлечённости не бывает.',
      });
    }
  } else if (mediaCollected) {
    out.push({
      key: 'no-discussion',
      label: 'Обсуждения нет',
      detail: 'Ни под одной записью и ни под одним роликом нет комментариев.',
      gain: 'Комментарии — то, по чему алгоритм отличает интересное от '
        + 'проходного. Начинается это обычно с прямого вопроса в конце поста.',
    });
  }

  // ------------------------------------------------------------- ритм
  if (m.per_week < 3) {
    out.push({
      key: 'rare',
      label: 'Постов выходит мало',
      detail: `${m.per_week.toFixed(1)} записей в неделю.`,
      gain: 'Алгоритму нужен регулярный сигнал: при трёх–пяти записях '
        + 'в неделю лента показывает страницу заметно чаще.',
    });
  }

  if (m.slots_used <= 2 && m.posts_own >= MIN_SAMPLE) {
    out.push({
      key: 'one-slot',
      label: 'Всё выходит в одно и то же время',
      detail: `Использовано слотов выхода: ${m.slots_used}.`,
      gain: 'Разные часы — разная аудитория. Пока пробуется один слот, '
        + 'вторая половина подписчиков страницу просто не видит.',
    });
  }

  // -------------------------------------------------------- чего не смотрели
  if (!mediaCollected) {
    out.push({
      key: 'media-not-collected',
      label: 'Медиа не разбирались',
      detail: 'Клипы, видео и фотографии в этом отчёте не читались.',
      gain: 'У ролика и снимка свои просмотры и свои реакции, которых нет '
        + 'в данных стены. Без них разбор видит меньше половины страницы.',
    });
  }

  if (!rivals?.rivals.length) {
    out.push({
      key: 'no-rivals',
      label: 'Сравнения с конкурентами нет',
      detail: 'Соседние страницы в этом отчёте не собирались.',
      gain: 'Без ориентира непонятно, «мало» это или «нормально для ниши»: '
        + 'ER в 1% бывает и провалом, и потолком — зависит от темы.',
    });
  }

  return out;
}
