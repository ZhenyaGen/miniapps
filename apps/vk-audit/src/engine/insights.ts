/** Зоны роста и пошаговый план: правила поверх посчитанных метрик. */

import type { Finding, Metrics, PlanStage, Profile, Severity, Target } from './types';
import { f, withSign } from './util';

/** Ориентиры для ВК — не абсолютная истина, а точка отсчёта для сравнения. */
export const BENCH = {
  er_views_low: 1.0,      // % вовлечённости к просмотрам
  er_views_good: 3.0,
  coverage_low: 15.0,     // средние просмотры к числу подписчиков, %
  coverage_good: 30.0,
  per_week_min: 3.0,
  per_week_max: 10.0,
  comment_ratio_low: 5.0, // доля комментариев в вовлечённости
  repost_ratio_low: 3.0,
  churn_high: 50.0,
  gap_cv_high: 1.0,
};

const SEVERITY_ORDER: Record<Severity, number> = { high: 0, mid: 1, low: 2 };

type Draft = Omit<Finding, 'rank' | 'priority'>;

function finding(
  id: string, area: string, title: string, severity: Severity, evidence: string,
  why: string, actions: string[], kpi: string, stage: number,
  impact = 2, effort = 2, blocker = false,
): Draft {
  return { id, area, title, severity, evidence, why, actions, kpi, stage, impact, effort, blocker };
}

export function findGrowthZones(m: Metrics, profile: Profile): Finding[] {
  const out: Draft[] = [];
  const kind = profile.kind;
  const audience = m.audience || 0;

  // ------------------------------------------------------------- 1. Упаковка
  const failed = m.profile_check.filter((c) => !c.ok);
  if (failed.length) {
    out.push(finding(
      'profile', 'Упаковка', 'Страница не дооформлена',
      failed.length >= 3 ? 'high' : 'mid',
      `Не заполнено: ${failed.map((c) => c.short).join(', ')}`,
      'Новый человек решает подписываться за 5–10 секунд, глядя на шапку. '
      + 'Пустые поля — потерянная конверсия из тех, кто уже дошёл до страницы.',
      failed.map((c) => c.hint),
      'Все пункты чек-листа упаковки — «готово»', 1, 3, 1));
  }

  if (m.empty) {
    out.push(finding(
      'no_posts', 'Контент', 'За период нет постов', 'high',
      `Ноль публикаций за ${m.period.days} дней`,
      'Без регулярного контента алгоритм ВК не показывает страницу в ленте, '
      + 'а подписчики забывают о ней за 2–3 недели.',
      ['Опубликуйте 3 поста на этой неделе: кто вы, чем полезны, свежий кейс',
       'Составьте контент-план на 4 недели вперёд по 3 поста в неделю'],
      '≥ 3 поста в неделю', 1, 3, 2));
    return finalize(out);
  }

  // ----------------------------------------------------------------- 2. Ритм
  const perWeek = m.per_week;
  if (perWeek < BENCH.per_week_min) {
    out.push(finding(
      'cadence', 'Ритм', 'Публикуете реже, чем нужно алгоритму', 'high',
      `${f(perWeek)} поста в неделю (ориентир — ${BENCH.per_week_min.toFixed(0)}–5)`,
      'Лента ВК ранжирует по свежести и накопленной реакции. Редкие посты не '
      + 'успевают набрать сигнал, и следующий пост стартует с более низкого охвата.',
      [`Поднять частоту до ${BENCH.per_week_min.toFixed(0)}–4 постов в неделю`,
       'Собрать банк из 10 тем и заранее написать 2 недели контента',
       'Закрепить фиксированные дни выхода — так проще держать ритм'],
      `${BENCH.per_week_min.toFixed(0)}+ поста в неделю`, 2, 3, 2));
  } else if (perWeek > BENCH.per_week_max) {
    out.push(finding(
      'cadence_high', 'Ритм', 'Постов много — они конкурируют друг с другом', 'mid',
      `${f(perWeek)} постов в неделю`,
      'При высокой частоте посты делят между собой один и тот же охват, '
      + 'средний ER падает, а часть аудитории скрывает записи из ленты.',
      ['Сократить до 4–6 сильных постов вместо потока',
       'Слабые форматы объединить в дайджест или сторис'],
      'ER на пост растёт при меньшем числе постов', 2, 2, 1));
  }

  if (m.gap.cv > BENCH.gap_cv_high && m.posts_total >= 6) {
    out.push(finding(
      'rhythm', 'Ритм', 'Публикации выходят рывками', 'mid',
      `Максимальная пауза — ${f(m.gap.max, 0)} дн. (${m.gap.max_range}), `
      + `медианный интервал — ${f(m.gap.median)} дн.`,
      'После длинной паузы охват первого поста падает: часть подписчиков '
      + 'перестаёт видеть страницу в ленте и её приходится «прогревать» заново.',
      ['Составить расписание и вести отложенный постинг в ВК',
       'Держать «запас» из 3 готовых постов на случай занятой недели'],
      'Разброс интервалов между постами < 1 дня к медиане', 2, 2, 1));
  }

  // -------------------------------------------------------- 3. Вовлечённость
  if (m.er_basis === 'views') {
    const er = m.er;
    let sev: Severity | null = null;
    if (er < BENCH.er_views_low) sev = 'high';
    else if (er < BENCH.er_views_good) sev = 'mid';
    if (sev) {
      out.push(finding(
        'er_low', 'Вовлечённость', 'Низкая вовлечённость к просмотрам', sev,
        `ER = ${f(er, 2)}% (ориентир — ${f(BENCH.er_views_good, 0)}%+), `
        + `медиана ${f(m.er_median, 2)}%`,
        'ER — главный сигнал для алгоритма. Пока он низкий, каждый следующий '
        + 'пост получает меньше показов, даже если аудитория растёт.',
        [`Заканчивать пост вопросом или явным призывом — сейчас это делает ${f(m.cta_share, 0)}% публикаций`,
         'Первые 2 строки переписать как крючок: лента показывает только их',
         'Повторить темы топ-5 постов из отчёта — они уже доказали спрос'],
        `ER ≥ ${f(Math.min(er * 1.5, BENCH.er_views_good), 1)}%`, 3, 3, 2));
    }
  } else if (audience && m.er_aud < 2.0) {
    out.push(finding(
      'er_aud_low', 'Вовлечённость', 'Мало реакций относительно аудитории', 'mid',
      `${f(m.avg.engagement, 1)} реакции на пост при ${f(audience, 0)} подписчиках `
      + `(${f(m.er_aud, 2)}% аудитории)`,
      'Просмотры по этой странице недоступны, поэтому считаем реакции к числу '
      + 'подписчиков. Низкое значение означает, что посты не доходят до ленты '
      + 'или не цепляют.',
      ['Заканчивать пост вопросом или явным призывом к действию',
       'Первые 2 строки переписать как крючок: лента показывает только их',
       'Повторить темы топ-5 постов из отчёта — они уже доказали спрос'],
      `Реакции на пост ≥ ${f(Math.max(m.avg.engagement * 1.5, 5), 0)}`, 3, 3, 2));
  }

  if (audience && m.views_per_audience < BENCH.coverage_low && m.avg.views) {
    out.push(finding(
      'coverage', 'Охват', 'Посты видит малая часть подписчиков', 'high',
      `Средние просмотры — ${f(m.avg.views, 0)} при ${f(audience, 0)} подписчиках `
      + `(${f(m.views_per_audience)}% аудитории)`,
      'Низкий охват своей же базы означает, что алгоритм считает контент '
      + 'неинтересным — либо аудитория набрана нецелевая.',
      ['Сделать 3 поста в формате, который в отчёте даёт максимальный ER',
       'Публиковать в лучшие слоты из тепловой карты',
       'Проверить, нет ли в подписчиках накрутки: резкие скачки без роста охвата'],
      `Охват ≥ ${BENCH.coverage_low.toFixed(0)}% аудитории`, 3, 3, 2));
  }

  if (m.comment_ratio < BENCH.comment_ratio_low) {
    out.push(finding(
      'comments', 'Вовлечённость', 'Почти нет диалога в комментариях', 'mid',
      `Комментарии — ${f(m.comment_ratio)}% всей вовлечённости `
      + `(${f(m.totals.comments, 0)} шт. за период)`,
      'Комментарий весит для алгоритма больше лайка и удерживает пост в ленте '
      + 'дольше. Их отсутствие — самый дешёвый резерв роста охвата.',
      ['Ввести 1 пост-вопрос в неделю с конкретным вопросом, а не «а как у вас?»',
       'Отвечать на каждый комментарий в первый час — ответы тоже считаются',
       'Пробовать опросы: они дают реакцию даже от молчаливых подписчиков'],
      `Доля комментариев ≥ ${BENCH.comment_ratio_low.toFixed(0)}%`, 3, 3, 1));
  }

  if (m.repost_ratio < BENCH.repost_ratio_low) {
    out.push(finding(
      'virality', 'Охват', 'Контент почти не репостят', 'mid',
      `Репосты — ${f(m.repost_ratio)}% вовлечённости (${f(m.totals.reposts, 0)} шт.)`,
      'Репост — единственный бесплатный способ выйти за пределы своей аудитории. '
      + 'Без него рост охвата упирается в число подписчиков.',
      ['Делать 1 «сохраняемый» пост в неделю: чек-лист, подборка, инструкция',
       'Добавлять в конец поста явное «сохрани/перешли тому, кому пригодится»',
       'Оформлять ключевые мысли карточками — их репостят чаще текста'],
      `Доля репостов ≥ ${BENCH.repost_ratio_low.toFixed(0)}%`, 3, 2, 2));
  }

  // -------------------------------------------------------------- 4. Форматы
  const types = m.by_type;
  if (types.length >= 2 && types[0].n >= 2) {
    const best = types[0];
    const worst = types[types.length - 1];
    if (best.avg_er && worst.avg_er && best.avg_er > worst.avg_er * 1.6) {
      out.push(finding(
        'format_mix', 'Форматы', `«${best.label}» работает заметно лучше остального`, 'mid',
        `${best.label}: ER ${f(best.avg_er, 2)}% при доле ${f(best.share, 0)}% постов. `
        + `${worst.label}: ER ${f(worst.avg_er, 2)}% при доле ${f(worst.share, 0)}%`,
        'Вы уже знаете, что заходит аудитории. Перекос ленты в сторону слабого '
        + 'формата — прямая потеря охвата на ровном месте.',
        [`Довести долю формата «${best.label.toLowerCase()}» минимум до 40% постов`,
         `Формат «${worst.label.toLowerCase()}» сократить или переупаковать`,
         'Проверить гипотезу на 4 постах и сравнить ER до/после'],
        `Доля «${best.label.toLowerCase()}» ≥ 40%`, 2, 3, 2));
    }
  }

  const video = types.find((t) => t.type === 'video');
  if (!video || video.share < 10) {
    out.push(finding(
      'video', 'Форматы', 'Видео почти не используется', 'mid',
      `Доля видео — ${video ? f(video.share, 0) : '0'}% постов`,
      'ВК приоритизирует видео и клипы в рекомендациях — это самый доступный '
      + 'источник охвата за пределами подписчиков.',
      ['Снять 4 вертикальных клипа до 60 секунд на темы топовых постов',
       'Выкладывать клип отдельной записью, а не вложением в текст',
       'Первые 3 секунды — суть, без длинных вступлений'],
      '≥ 1 видео/клип в неделю', 3, 3, 3));
  }

  if (m.reposts_share > 30 && kind === 'group') {
    out.push(finding(
      'reposts_own', 'Контент', 'Много чужого контента вместо своего', 'mid',
      `${f(m.reposts_share, 0)}% записей — репосты`,
      'Чужие записи набирают меньше и не строят узнаваемость. Алгоритм '
      + 'показывает их слабее, чем оригинальный контент.',
      ['Довести долю собственных постов до 80%',
       'Чужой материал переупаковывать: своя мысль + короткая цитата'],
      'Доля своих постов ≥ 80%', 2, 2, 2));
  }

  // ---------------------------------------------------------------- 5. Время
  if (m.best_slots.length && m.worst_slots.length) {
    const best = m.best_slots[0];
    const worst = m.worst_slots[0];
    if (best.avg_er > worst.avg_er * 1.8) {
      out.push(finding(
        'timing', 'Время', 'Часть постов выходит в слабое время', 'mid',
        `Лучший слот — ${best.label} (ER ${f(best.avg_er, 2)}%), `
        + `худший — ${worst.label} (ER ${f(worst.avg_er, 2)}%)`,
        'Первый час решает: если пост не собрал реакции сразу, лента '
        + 'перестаёт его показывать.',
        [`Ставить ключевые посты в слоты: ${m.best_slots.slice(0, 2).map((s) => s.label).join(', ')}`,
         `Не публиковать в ${worst.label}`,
         'Проверить гипотезу минимум на 6 постах — слоты считаются по вашим данным'],
        'Все ключевые посты — в топ-2 слота', 2, 2, 1));
    }
  }

  // --------------------------------------------------------------- 6. Тексты
  const lengths = m.by_length.filter((b) => b.n >= 2);
  if (lengths.length >= 2) {
    const bestLen = lengths.reduce((a, b) => (b.avg_er > a.avg_er ? b : a));
    const cur = lengths.reduce((a, b) => (b.n > a.n ? b : a));
    if (bestLen.label !== cur.label && bestLen.avg_er > cur.avg_er * 1.4) {
      out.push(finding(
        'length', 'Тексты', 'Длина постов не совпадает с тем, что заходит', 'low',
        `Чаще всего пишете «${cur.label}» знаков (ER ${f(cur.avg_er, 2)}%), `
        + `а лучший ER у «${bestLen.label}» (ER ${f(bestLen.avg_er, 2)}%)`,
        'Формат чтения в ленте задан привычкой аудитории — стоит подстроиться '
        + 'под ту длину, которую она реально дочитывает.',
        [`Следующие 5 постов писать в объёме «${bestLen.label}» знаков`,
         'Длинные материалы выносить в статьи ВК со ссылкой из короткого поста'],
        `Основной объём постов — «${bestLen.label}» знаков`, 3, 1, 1));
    }
  }

  if (m.cta_share < 30) {
    out.push(finding(
      'cta', 'Тексты', 'В постах редко есть призыв к действию', 'mid',
      `Явный призыв — только в ${f(m.cta_share, 0)}% постов, `
      + `вопрос — в ${f(m.questions_share, 0)}%`,
      'Люди делают то, о чём их прямо просят. Без финального действия пост '
      + 'прочитывают и пролистывают, не оставляя алгоритму сигнала.',
      ['В каждый пост добавить одно конкретное действие в конце',
       'Чередовать действия: вопрос → сохранение → переход по ссылке'],
      'Призыв в ≥ 70% постов', 3, 2, 1));
  }

  // ------------------------------------------------------------- 7. Хэштеги
  const hs = m.hashtags;
  if (hs && hs.share_with < 20) {
    out.push(finding(
      'hashtags', 'Навигация', 'Нет системы хэштегов', 'low',
      `Хэштеги есть в ${f(hs.share_with, 0)}% постов, уникальных — ${hs.unique}`,
      'Хэштеги в ВК работают как навигация по рубрикам: подписчик может '
      + 'провалиться в интересную ему серию и прочитать 5 постов вместо одного.',
      ['Завести 4–6 рубрик и подписывать каждый пост одним рубричным тегом',
       'Вынести список рубрик в закреплённый пост или меню'],
      'Рубричный тег в 100% постов', 2, 1, 1));
  }

  // -------------------------------------------------------------- 8. Тренды
  const tr = m.trend;
  if (tr.er !== null && tr.er < -20) {
    out.push(finding(
      'er_trend', 'Динамика', 'Вовлечённость падает от месяца к месяцу', 'high',
      `ER второй половины периода к первой: ${f(tr.er, 0)}%`,
      'Падение ER при неизменной аудитории означает выгорание формата: '
      + 'подписчики привыкли и перестали реагировать.',
      ['Сравнить топ-посты первой и второй половины периода и найти, что ушло',
       'Ввести один новый формат и вести его 4 недели подряд',
       'Почистить рубрики с ER ниже среднего'],
      'ER возвращается к уровню начала периода', 3, 3, 2));
  }
  if (tr.views !== null && tr.views < -25) {
    out.push(finding(
      'views_trend', 'Динамика', 'Просмотры снижаются', 'high',
      `Средние просмотры второй половины периода к первой: ${f(tr.views, 0)}%`,
      'Просмотры падают раньше, чем подписчики: алгоритм сокращает показы '
      + 'до того, как люди начнут отписываться.',
      ['Проверить, не совпало ли падение с паузой в публикациях',
       'Вернуть частоту и форматы того периода, когда просмотры были выше'],
      'Просмотры на уровне лучшего месяца периода', 3, 3, 2));
  }

  // --------------------------------------------- 9. Данные сообщества (stats)
  const gs = m.group_stats;
  if (gs) {
    if (gs.churn > BENCH.churn_high && gs.subscribed > 10) {
      out.push(finding(
        'churn', 'Аудитория', 'Высокая отписка', 'high',
        `Подписалось ${gs.subscribed}, отписалось ${gs.unsubscribed} `
        + `(отток ${f(gs.churn, 0)}% от прироста)`,
        'Отписки сразу после подписки означают, что ожидание от страницы '
        + 'не совпадает с контентом — либо трафик приходит нецелевой.',
        ['Сверить обещание в шапке с тем, что реально выходит в ленте',
         'Посмотреть посты в дни пиковых отписок и убрать этот формат',
         'Если идёт реклама — сузить таргетинг под тему страницы'],
        `Отток < ${BENCH.churn_high.toFixed(0)}% от прироста`, 1, 3, 2));
    } else if (gs.net <= 0 && gs.days.length) {
      out.push(finding(
        'growth_flat', 'Аудитория', 'Аудитория не растёт', 'high',
        `Чистый прирост за период: ${withSign(gs.net)} подписчиков`,
        'Без притока новых людей охват упирается в потолок текущей базы, '
        + 'и любое падение ER сразу бьёт по результату.',
        ['Запустить один канал привлечения: посевы, реклама или коллаборации',
         'Сделать закреплённый пост-знакомство с явной причиной подписаться'],
        'Положительный прирост каждую неделю', 4, 3, 3));
    }
  }

  const reach = m.reach;
  if (reach && reach.viral_share < 10 && reach.posts >= 5) {
    out.push(finding(
      'viral_reach', 'Охват', 'Охват держится только на подписчиках', 'mid',
      `Виральный охват — ${f(reach.viral_share, 0)}% от общего `
      + `(в среднем ${f(reach.avg_total, 0)} человек на пост)`,
      'Виральная часть охвата — это показы людям, которые на вас не подписаны. '
      + 'Она показывает, есть ли у контента шанс на органический рост.',
      ['Делать посты, полезные вне контекста страницы: инструкции, разборы',
       'Тестировать «Продвижение» на постах с лучшим органическим ER'],
      'Виральный охват ≥ 20%', 4, 2, 2));
  }

  out.push(...moreRules(m, profile));
  return finalize(out);
}

/** Вторая группа правил: закреп, однообразие, стабильность, гигиена. */
function moreRules(m: Metrics, profile: Profile): Draft[] {
  const out: Draft[] = [];
  const kind = profile.kind;
  const postsN = m.posts_total;

  // ------------------------------------------------- молчание и накрутка
  const silent = m.silent_days;
  if (silent > 30 && postsN) {
    out.push(finding(
      'silence', 'Ритм', 'Страница молчит', 'high',
      `Последняя публикация была ${f(silent, 0)} дней назад. `
      + `За период вышло ${postsN} постов — это ${f(m.per_week_period)} `
      + 'в неделю в пересчёте на весь срок',
      'После месяца тишины лента перестаёт показывать страницу даже '
      + 'подписчикам: набранный охват обнуляется, и первые посты после '
      + 'паузы выходят почти в пустоту.',
      ['Вернуться к публикациям в ближайшие дни, не дожидаясь «идеального» поста',
       'Первые две недели держать 3 поста в неделю — алгоритму нужен сигнал',
       'Начать с формата, который в отчёте даёт лучший ER'],
      'Последний пост не старше 5 дней', 1, 3, 2, true));
  }

  const coverage = m.views_per_audience;
  const er = m.er;
  if (m.er_basis === 'views' && er > 15 && coverage < 10 && postsN >= 5) {
    out.push(finding(
      'fake_engagement', 'Аудитория', 'Реакций подозрительно много для такого охвата', 'high',
      `ER ${f(er, 1)}% при охвате ${f(coverage, 1)}% аудитории: посты видит `
      + `${f(m.avg.views, 0)} человек из ${f(m.audience, 0)} `
      + `подписчиков, а реакций — ${f(m.avg.engagement, 1)} на пост`,
      'Живая аудитория так себя не ведёт: обычно ER к просмотрам держится '
      + 'в пределах 3–10%. Сочетание «мало показов, много лайков» почти всегда '
      + 'означает накрутку подписчиков или реакций. Накрученная база не читает '
      + 'посты, зато занижает охват: алгоритм видит, что записи не смотрят.',
      ['Сверить число подписчиков с числом просмотров: если разрыв больше '
       + 'десяти раз — база в основном мёртвая',
       'Проверить, не покупались ли подписчики или лайки ранее',
       'Не гнаться за приростом подписчиков, пока не вырастет охват: '
       + 'чистить базу и работать на живых',
       'Ориентироваться на просмотры и комментарии, а не на лайки'],
      'Охват ≥ 15% аудитории при ER в пределах 3–10%', 1, 3, 3));
  }

  // --------------------------------------------------- закреплённый пост
  const pinned = m.pinned;
  if (!pinned.exists) {
    out.push(finding(
      'pinned_none', 'Упаковка', 'Нет закреплённого поста', 'mid',
      'Ни одна запись за период не закреплена',
      'Закреплённый пост — единственный, который новый человек гарантированно '
      + 'увидит первым. Без него он попадает на случайную запись и уходит.',
      ['Сделать пост-знакомство: кто вы, чем полезны, что делать дальше',
       'Закрепить его и обновлять раз в 1–2 месяца под текущую задачу'],
      'Закреплённый пост есть и не старше 2 месяцев', 1, 3, 1));
  } else if ((pinned.age_days ?? 0) > 120) {
    out.push(finding(
      'pinned_old', 'Упаковка', 'Закреплённый пост устарел', 'low',
      `Закреплённой записи ${f(pinned.age_days ?? 0, 0)} дней`,
      'Старый закреп показывает новичкам неактуальную картину: акция кончилась, '
      + 'анонс прошёл, а именно это они видят первым.',
      ['Заменить закреп на актуальный оффер или свежий сильный пост',
       'Поставить напоминание обновлять его раз в месяц'],
      'Закреп не старше 60 дней', 1, 2, 1));
  }

  // ----------------------------------------------------------- однообразие
  const dom = m.dominant_format;
  if (dom && dom.share > 70 && postsN >= 8) {
    out.push(finding(
      'format_monotony', 'Форматы', 'Лента однообразная', 'mid',
      `${f(dom.share, 0)}% записей — один формат «${dom.label.toLowerCase()}»`,
      'Однотипная лента приедается: подписчик перестаёт задерживаться на записи, '
      + 'а алгоритм считает это снижением интереса и режет показы.',
      ['Добавить 2 новых формата в ротацию: опрос, видео, карточки',
       'Держать правило: не больше 50% ленты на один формат'],
      'Доля самого частого формата < 50%', 2, 2, 2));
  }

  if (m.polls === 0 && postsN >= 8) {
    out.push(finding(
      'polls', 'Форматы', 'Ни одного опроса за период', 'low',
      'Опросов: 0',
      'Опрос — самый дешёвый способ получить реакцию: голосуют даже те, кто '
      + 'никогда не пишет комментарии и не ставит лайки.',
      ['Ставить 1 опрос в 2 недели: выбор темы, формата или мнение по вопросу',
       'Результат опроса потом разбирать отдельным постом'],
      '1–2 опроса в месяц', 3, 2, 1));
  }

  if (postsN >= 10 && m.slots_used <= 3) {
    out.push(finding(
      'time_monotony', 'Время', 'Время выхода почти не менялось', 'low',
      `Все посты укладываются в ${m.slots_used} слота из 56 возможных`,
      'Пока вы публикуете в одно и то же время, вы не знаете, где ваш реальный '
      + 'пик активности — и, возможно, годами теряете охват на ровном месте.',
      ['Провести тест: 6 постов в трёх разных слотах и сравнить ER',
       'Через месяц закрепить победивший слот как основной'],
      'Проверено минимум 3 разных слота', 2, 2, 1));
  }

  if (postsN >= 10 && m.dow_used <= 2) {
    out.push(finding(
      'dow_narrow', 'Время', 'Публикации только в одни и те же дни', 'low',
      `Задействовано дней недели: ${m.dow_used} из 7`,
      'Аудитория заходит в ВК в разные дни. Узкое окно публикаций означает, '
      + 'что часть подписчиков системно вас не видит.',
      ['Расширить график минимум до 3 дней недели',
       'Проверить выходные: там ниже конкуренция в ленте'],
      'Посты минимум в 3 разных дня недели', 2, 2, 1));
  }

  // ----------------------------------------------------------- стабильность
  if (postsN >= 8 && m.er_stability < 0.6) {
    out.push(finding(
      'er_unstable', 'Вовлечённость', 'Результат держится на единичных постах', 'mid',
      `Медиана ER — ${f(m.er_median, 2)}% при среднем ${f(m.er, 2)}%`,
      'Средний ER вытягивают один-два удачных поста, а типичная запись слабее. '
      + 'Планировать рост по среднему в такой ситуации — значит обманывать себя.',
      ['Разобрать, что общего у постов выше медианы, и повторить это',
       'Ориентироваться на медиану, а не на среднее — она честнее'],
      'Медиана не ниже 80% от среднего', 3, 2, 2));
  }

  if (postsN >= 8 && m.views_cv > 0.8) {
    out.push(finding(
      'views_unstable', 'Охват', 'Просмотры скачут от поста к посту', 'low',
      `Разброс просмотров — ${f(m.views_cv * 100, 0)}% от среднего`,
      'Нестабильный охват обычно означает рваный график или смешение разных тем: '
      + 'алгоритм не может понять, кому показывать страницу.',
      ['Выровнять график публикаций — это главная причина скачков',
       'Свести темы к 3–4 рубрикам вместо разрозненных постов'],
      'Разброс просмотров < 60%', 2, 2, 2));
  }

  if (m.totals.views && m.like_rate < 1.0) {
    out.push(finding(
      'like_rate', 'Вовлечённость', 'Посты читают, но не реагируют', 'mid',
      `Лайков — ${f(m.like_rate, 2)}% от просмотров`,
      'Просмотр без реакции — сигнал алгоритму, что контент проходной. '
      + 'Тут проблема не в охвате, а в самом содержании поста.',
      ['Сильную мысль выносить в первые две строки, а не в конец',
       'Один пост — одна мысль: длинные многотемные посты не дочитывают',
       'Добавить прямую просьбу отреагировать в конце'],
      'Лайков ≥ 2% от просмотров', 3, 3, 2));
  }

  // ---------------------------------------------------------------- гигиена
  const last30 = m.last30;
  if (last30.expected >= 3 && last30.posts < last30.expected * 0.5) {
    out.push(finding(
      'slowdown', 'Ритм', 'За последний месяц публикаций стало меньше', 'high',
      `За 30 дней — ${last30.posts} постов при обычных ${f(last30.expected, 0)}`,
      'Спад частоты алгоритм замечает быстрее людей: охват начинает падать '
      + 'уже на второй-третьей неделе затишья.',
      ['Вернуть привычную частоту на ближайшие 2 недели',
       'Заготовить 4 поста впрок, чтобы занятость не обнуляла график'],
      'Частота вернулась к обычной', 2, 3, 2));
  }

  if (m.ads_share > 20) {
    out.push(finding(
      'ads', 'Контент', 'Много рекламных записей', 'mid',
      `${f(m.ads_share, 0)}% постов помечены как реклама`,
      'Рекламные записи ВК показывает подписчикам хуже обычных, а аудитория '
      + 'быстрее отписывается, если лента похожа на витрину.',
      ['Держать долю рекламы не выше 15–20% записей',
       'Между рекламными постами ставить два полезных'],
      'Доля рекламы ≤ 15%', 2, 2, 1));
  }

  if (m.repeat_share > 25 && postsN >= 10) {
    out.push(finding(
      'repeats', 'Контент', 'Посты повторяют друг друга', 'low',
      `${f(m.repeat_share, 0)}% записей начинаются одинаково`,
      'Повторяющиеся начала выглядят как копипаста: человек узнаёт формулировку '
      + 'и пролистывает, не читая.',
      ['Переписать шаблонные вступления — каждый пост со своей первой строки',
       'Вести список использованных зацепок, чтобы не повторяться'],
      'Повторов < 10%', 3, 1, 1));
  }

  if (m.tags_per_post > 7) {
    out.push(finding(
      'hashtag_spam', 'Навигация', 'Слишком много хэштегов', 'low',
      `В среднем ${f(m.tags_per_post, 1)} тега на пост`,
      'Простыня тегов читается как спам и не помогает навигации: работают '
      + '2–4 осмысленных рубричных тега.',
      ['Оставить 1 рубричный тег и 1–2 тематических',
       'Остальные убрать — они не приносят охвата'],
      '2–4 тега на пост', 2, 1, 1));
  }

  if (m.links_share < 10 && kind === 'group') {
    out.push(finding(
      'no_links', 'Конверсия', 'В постах почти нет ссылок', 'mid',
      `Ссылки есть в ${f(m.links_share, 0)}% записей`,
      'Если у ленты нет выхода — на сайт, в личные сообщения, на форму — '
      + 'вовлечённость не превращается ни в заявки, ни в продажи.',
      ['В каждый третий пост добавлять понятную точку выхода',
       'Проверить, что в шапке и меню сообщества есть та же ссылка'],
      'Ссылка в 30% постов', 3, 2, 1));
  }

  if (profile.is_closed) {
    out.push(finding(
      'closed', 'Упаковка', 'Страница закрыта от посторонних', 'high',
      'Профиль или сообщество в закрытом режиме',
      'Закрытая страница не индексируется, не попадает в рекомендации и не даёт '
      + 'новому человеку понять, стоит ли подписываться.',
      ['Открыть страницу, если она ведётся для аудитории, а не для друзей',
       'Личное оставить в закрытом альбоме или в другом аккаунте'],
      'Страница открыта', 1, 3, 1));
  }

  const reach = m.reach;
  if (reach && reach.posts >= 5 && reach.hides > reach.joins) {
    out.push(finding(
      'hides', 'Аудитория', 'Записи скрывают чаще, чем подписываются', 'mid',
      `Скрытий: ${reach.hides}, подписок с постов: ${reach.joins}`,
      'Скрытие — самый жёсткий негативный сигнал: после него ВК почти '
      + 'перестаёт показывать страницу этому человеку.',
      ['Посмотреть посты в дни пиковых скрытий и убрать этот тип контента',
       'Снизить частоту, если постов больше 7 в неделю'],
      'Подписок с постов больше, чем скрытий', 3, 3, 2));
  }

  return out;
}

/**
 * Порядок — по важности и отдаче на усилие, но блокирующая находка идёт
 * первой: пока страница молчит, остальные улучшения ничего не дадут.
 */
function finalize(drafts: Draft[]): Finding[] {
  const sorted = drafts
    .map((item, i) => ({ item, i }))
    .sort((a, b) => {
      const blocker = (a.item.blocker ? 1 : 0) - (b.item.blocker ? 1 : 0);
      if (blocker) return -blocker;
      const severity = SEVERITY_ORDER[a.item.severity] - SEVERITY_ORDER[b.item.severity];
      if (severity) return severity;
      const priority = (b.item.impact * 2 - b.item.effort) - (a.item.impact * 2 - a.item.effort);
      if (priority) return priority;
      return a.i - b.i;
    })
    .map(({ item }) => item);

  return sorted.map((item, i) => ({
    ...item,
    rank: i + 1,
    priority: item.impact * 2 - item.effort,
  }));
}

