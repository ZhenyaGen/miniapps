const STAGES: Array<[number, string, string]> = [
  [1, 'Неделя 1 · Упаковка и гигиена',
   'Убрать всё, что теряет людей, уже дошедших до страницы'],
  [2, 'Неделя 2 · Ритм и структура контента',
   'Зафиксировать частоту, форматы и время выхода'],
  [3, 'Неделя 3 · Вовлечённость',
   'Поднять реакции на пост — главный сигнал для алгоритма ВК'],
  [4, 'Неделя 4 · Рост аудитории и замер',
   'Подключить приток новых людей и сверить результат с точкой старта'],
];

const BASELINE_TASKS: Record<number, string[]> = {
  1: ['Зафиксировать точку старта: подписчики, средние просмотры, ER — из этого отчёта',
      'Обновить закреплённый пост: кто вы, чем полезны, что делать дальше'],
  2: ['Составить контент-план на 4 недели: рубрика × день недели',
      'Настроить отложенный постинг на всю неделю вперёд'],
  3: ['Отвечать на все комментарии в течение часа после выхода поста',
      'Сравнить ER постов этой недели с прошлой и оставить то, что сработало'],
  4: ['Пересобрать отчёт этой же командой и сравнить метрики с первой неделей',
      'Оставить 2 формата-победителя и убрать 1 самый слабый'],
};

export function buildPlan(findings: Finding[], m: Metrics): PlanStage[] {
  return STAGES.map(([stage, title, goal]) => {
    const tasks = findings
      .filter((f_) => f_.stage === stage)
      .flatMap((f_) => f_.actions.map((action) => ({
        text: action,
        source: f_.title,
        severity: f_.severity,
      })));
    const baseTasks = BASELINE_TASKS[stage].map((text) => ({
      text,
      source: 'База',
      severity: 'low' as Severity,
    }));
    return {
      stage,
      title,
      goal,
      tasks: [...tasks.slice(0, 9 - baseTasks.length), ...baseTasks],
      metric: stageMetric(stage, m),
    };
  });
}

function stageMetric(stage: number, m: Metrics): string {
  if (stage === 1) {
    const done = m.profile_check.filter((c) => c.ok).length;
    return `Чек-лист упаковки: ${done}/${m.profile_check.length} → 100%`;
  }
  if (stage === 2) return `Частота: ${f(m.per_week)} → 3–4 поста в неделю`;
  if (stage === 3) {
    if (m.er_basis === 'views') {
      return `ER: ${f(m.er, 2)}% → ${f(Math.max(m.er * 1.5, 1.5), 2)}%`;
    }
    return `Вовлечённость на пост: ${f(m.avg.engagement, 0)} → ${f(m.avg.engagement * 1.5, 0)}`;
  }
  return `Просмотры на пост: ${f(m.avg.views, 0)} → ${f(m.avg.views * 1.3, 0)}`;
}

/** Цели на 90 дней — от текущих значений, а не «средних по рынку». */
export function buildTargets(m: Metrics): Target[] {
  if (m.empty) return [{ label: 'Публикации', now: '0 в неделю', goal: '3 в неделю' }];

  const targets: Target[] = [{
    label: 'Частота публикаций',
    now: `${f(m.per_week)} / нед.`,
    goal: `${Math.max(3, Math.round(m.per_week)).toFixed(0)} / нед.`,
  }];
  if (m.er_basis === 'views') {
    targets.push({
      label: 'ER к просмотрам',
      now: `${f(m.er, 2)}%`,
      goal: `${f(Math.max(m.er * 1.5, 1.5), 2)}%`,
    });
  }
  targets.push(
    { label: 'Просмотры на пост', now: f(m.avg.views, 0), goal: f(m.avg.views * 1.4, 0) },
    {
      label: 'Комментарии на пост',
      now: f(m.avg.comments, 1),
      goal: f(Math.max(m.avg.comments * 2, 3), 1),
    },
    {
      label: 'Репосты на пост',
      now: f(m.avg.reposts, 1),
      goal: f(Math.max(m.avg.reposts * 2, 2), 1),
    },
  );
  if (m.audience) {
    const label = m.audience_label.charAt(0).toUpperCase() + m.audience_label.slice(1);
    targets.push({ label, now: f(m.audience, 0), goal: f(m.audience * 1.15, 0) });
  }
  return targets;
}
